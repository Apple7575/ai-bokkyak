-- 보호자 기능 제거에 따른 patients.patient_code 정리
--
-- 배경: 보호자가 6자리 코드를 입력해 환자를 읽기 전용으로 본다는 기능은
--       설계 문서에만 있었고 화면이 만들어진 적이 없다. 기능을 접기로 했다.
--       앱은 이제 가입할 때 patient_code 를 보내지 않는다.
--
-- ⚠️ 1단계는 반드시 실행해야 한다. patient_code 가 not null 인 채로 새 앱을
--    올리면 가입 insert 가 전부 실패한다. 앱 배포 전에 먼저 돌릴 것.

-- ── 1단계 (필수) ────────────────────────────────────────────────
-- 값을 안 보내도 insert 가 되도록 제약만 푼다.
-- 기존 행의 코드는 그대로 남으므로 되돌리기 쉽다.
alter table patients alter column patient_code drop not null;

-- unique 제약은 그대로 둬도 된다 — 포스트그레스는 null 을 여러 개 허용한다.


-- ── 2단계 (선택) ────────────────────────────────────────────────
-- 컬럼을 아예 지운다. 되돌릴 수 없고 기존 코드 값이 사라진다.
-- 1단계로 앱이 정상 동작하는 것을 확인한 뒤에 실행할 것.
--
-- alter table patients drop column patient_code;
